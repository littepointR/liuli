#!/usr/bin/env python3
"""Zero-dependency compiler from JSON i18n catalogs to #![no_std] Rust LocaleTable modules."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

PLACEHOLDER_RE = re.compile(r"(?<!\{)\{(\d+)\}(?!\})")


def load_catalog(input_path: Path) -> dict[str, dict[str, str]]:
    if input_path.is_dir():
        catalog: dict[str, dict[str, str]] = {}
        for p in sorted(input_path.glob("*.json")):
            data = json.loads(p.read_text(encoding="utf-8"))
            if not isinstance(data, dict):
                raise ValueError(f"{p}: expected JSON object")
            catalog[p.stem] = {str(k): str(v) for k, v in data.items()}
        if not catalog:
            raise ValueError(f"no *.json catalogs found in {input_path}")
        return catalog
    data = json.loads(input_path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{input_path}: expected object mapping locale codes to key->string maps")
    return {
        str(loc): {str(k): str(v) for k, v in entries.items()}
        for loc, entries in data.items()
    }


def rust_const_ident(key: str) -> str:
    ident = re.sub(r"[^A-Za-z0-9_]", "_", key).upper()
    if not ident or ident[0].isdigit():
        ident = "K_" + ident
    return ident


def escape_rust_str(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def validate_catalog(catalog: dict[str, dict[str, str]], default_locale: str) -> list[str]:
    if default_locale not in catalog:
        raise ValueError(f"default locale '{default_locale}' missing from catalog")
    base_keys = sorted(catalog[default_locale].keys())
    errors: list[str] = []
    for key in base_keys:
        base_args = sorted(set(PLACEHOLDER_RE.findall(catalog[default_locale][key])))
        for loc, entries in catalog.items():
            if loc == default_locale:
                continue
            val = entries.get(key)
            if not val:
                errors.append(f"locale '{loc}' missing non-empty translation for '{key}'")
            else:
                loc_args = sorted(set(PLACEHOLDER_RE.findall(val)))
                if loc_args != base_args:
                    errors.append(
                        f"locale '{loc}' key '{key}' placeholders {loc_args} != base {base_args}"
                    )
    return errors


def generate_rust(catalog: dict[str, dict[str, str]], default_locale: str) -> str:
    ordered_locales = [default_locale] + sorted(k for k in catalog if k != default_locale)
    all_keys = sorted({k for entries in catalog.values() for k in entries})

    lines = [
        "// Auto-generated by tools/liuli-i18n.py — do not edit by hand.",
        "use liuli_core::i18n::{LocaleId, LocaleTable, TextKey};",
        "",
    ]
    for loc_idx, loc in enumerate(ordered_locales):
        lines.append(f"pub const LOCALE_{rust_const_ident(loc)}: LocaleId = LocaleId({loc_idx});")
    lines.append("")
    lines.append("pub mod keys {")
    lines.append("    use super::TextKey;")
    for key_idx, key in enumerate(all_keys):
        lines.append(f"    pub const {rust_const_ident(key)}: TextKey = TextKey({key_idx});")
    lines.append("}")
    lines.append("")
    for loc in ordered_locales:
        entries = catalog[loc]
        ident = rust_const_ident(loc)
        lines.append(f"static ENTRIES_{ident}: &[&str] = &[")
        for key in all_keys:
            val = escape_rust_str(entries.get(key, ""))
            lines.append(f'    "{val}", // {key}')
        lines.append("];")
    lines.append("")
    lines.append("pub static LOCALES: &[LocaleTable] = &[")
    for loc in ordered_locales:
        ident = rust_const_ident(loc)
        lines.append(f'    LocaleTable::new("{escape_rust_str(loc)}", ENTRIES_{ident}),')
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def run_self_test() -> int:
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        (d / "en.json").write_text(
            json.dumps({"hello": "Hi {0}", "ok": "OK"}, ensure_ascii=False),
            encoding="utf-8",
        )
        (d / "zh.json").write_text(
            json.dumps({"hello": "你好 {0}", "ok": "确定"}, ensure_ascii=False),
            encoding="utf-8",
        )
        cat = load_catalog(d)
        assert not validate_catalog(cat, "en")
        rust_src = generate_rust(cat, "en")
        assert "pub const HELLO: TextKey = TextKey(0);" in rust_src
        assert "pub const OK: TextKey = TextKey(1);" in rust_src
        assert 'LocaleTable::new("zh"' in rust_src

        (d / "zh.json").write_text(
            json.dumps({"hello": "你好 {1}", "ok": ""}, ensure_ascii=False),
            encoding="utf-8",
        )
        bad_issues = validate_catalog(load_catalog(d), "en")
        assert len(bad_issues) == 2, bad_issues
    print("liuli-i18n self-test OK")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Compile i18n JSON catalogs into #![no_std] Rust.")
    parser.add_argument("--input", type=Path, help="JSON catalog file or directory")
    parser.add_argument("--output", type=Path, help="Destination .rs path")
    parser.add_argument("--default-locale", help="Primary fallback locale code")
    parser.add_argument("--check", action="store_true", help="Fail if translations/placeholders mismatch")
    parser.add_argument("--self-test", action="store_true", help="Run internal compiler checks")
    args = parser.parse_args()

    if args.self_test:
        return run_self_test()
    if not args.input:
        parser.error("--input is required unless --self-test is set")

    catalog = load_catalog(args.input)
    default_locale = args.default_locale or ("en" if "en" in catalog else sorted(catalog)[0])
    issues = validate_catalog(catalog, default_locale)
    if args.check and issues:
        for msg in issues:
            print(f"i18n error: {msg}", file=sys.stderr)
        return 1
    for msg in issues:
        print(f"i18n warning: {msg}", file=sys.stderr)

    rust_src = generate_rust(catalog, default_locale)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rust_src, encoding="utf-8", newline="\n")
    else:
        print(rust_src)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
